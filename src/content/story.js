// Сюжет игры: спуск по пещерам Графа Пропсулы — от простого к сложному.
// Чем глубже ярус, тем сложнее тема: знания верхних пещер нужны в нижних.
// У каждой пещеры свой хозяин-чудище, а над всеми — Граф. Облик хозяина
// подсказывает тему (сороконожка — массив, богомол с крюками — хуки):
// яркий образ, привязанный к месту, вспоминается легче (метод локусов +
// эффект необычного). Эмоции и сюжет помогают запоминать, а незаконченная
// история тянет пройти дальше (эффект Зейгарник).

